package main

import (
	"encoding/binary"
	"fmt"
	"strings"
)

// ---------------------------------------------------------------- Crackme v3

const crackmeSerial = "SK3V-0R4Y-L1V3-9X2Q"

func rol1(v byte) byte { return v<<1 | v>>7 }

// crackme writes src/data.h: the serial check is a rolling XOR against a
// table, and the flag is stored XOR'd with the serial.
func crackme() {
	r := rng("crackme-v3")
	table := make([]byte, 16)
	_, _ = r.Read(table)
	expect := make([]byte, len(crackmeSerial))
	acc := byte(0x5a)
	for i := range len(crackmeSerial) {
		acc = rol1(acc) ^ crackmeSerial[i] ^ table[i%16]
		expect[i] = acc
	}
	flagText := "flag{serial_killer_v3}"
	enc := make([]byte, len(flagText))
	for i := range enc {
		enc[i] = flagText[i] ^ crackmeSerial[i%len(crackmeSerial)] ^ byte(i*7)
	}
	var b strings.Builder
	b.WriteString("/* Generated by challenges/sample/tools/gen. Don't edit. */\n")
	fmt.Fprintf(&b, "#define SERIAL_LEN %d\n#define FLAG_LEN %d\n", len(crackmeSerial), len(flagText))
	b.WriteString("static const unsigned char TABLE[16] = {" + cBytes(table) + "};\n")
	b.WriteString("static const unsigned char EXPECT[SERIAL_LEN] = {" + cBytes(expect) + "};\n")
	b.WriteString("static const unsigned char ENC[FLAG_LEN] = {" + cBytes(enc) + "};\n")
	write("crackme-v3/src/data.h", []byte(b.String()))
}

func cBytes(b []byte) string {
	parts := make([]string, len(b))
	for i, v := range b {
		parts[i] = fmt.Sprintf("0x%02x", v)
	}
	return strings.Join(parts, ",")
}

// ---------------------------------------------------------------- Obfuscated Oracle
//
// A stack machine with 14 opcodes. The opcode values are shuffled, and every
// byte of the program is XOR'd with (0x5a + 13*position), so the file looks
// like noise until the interpreter is understood.

var vmOps = []string{"HALT", "PUSH", "POP", "DUP", "SWAP", "ADD", "SUB", "XOR", "MUL", "LOAD", "LEN", "JMP", "JZ", "JNZ"}

type asm struct {
	code   []byte
	op     map[string]byte
	labels map[string]int
	fixups map[int]string // position of an int16 operand -> label
}

func (a *asm) emit(op string, imm ...byte) {
	a.code = append(append(a.code, a.op[op]), imm...)
}

func (a *asm) jump(op, label string) {
	a.code = append(a.code, a.op[op], 0, 0)
	a.fixups[len(a.code)-2] = label
}

func oracle() {
	r := rng("obfuscated-oracle")
	a := &asm{op: map[string]byte{}, labels: map[string]int{}, fixups: map[int]string{}}
	// Shuffled opcode values, all distinct.
	perm := r.Perm(256)
	var defs strings.Builder
	defs.WriteString("/* Generated by challenges/sample/tools/gen. Don't edit. */\n")
	for i, name := range vmOps {
		a.op[name] = byte(perm[i])
		fmt.Fprintf(&defs, "#define OP_%s 0x%02x\n", name, perm[i])
	}

	flagText := "flag{lifted_the_bytecode}"
	// len(input) must be 25.
	a.emit("LEN")
	a.emit("PUSH", byte(len(flagText)))
	a.emit("SUB")
	a.jump("JNZ", "fail")
	// For each i: ((in[i] ^ k) * m + previous) & 0xff == t, where previous
	// is in[i-1] (0x33 for the first character).
	for i := range len(flagText) {
		k, m := byte(r.IntN(256)), byte(r.IntN(128)*2+1)
		prev := byte(0x33)
		if i > 0 {
			prev = flagText[i-1]
		}
		t := (flagText[i]^k)*m + prev
		a.emit("PUSH", byte(i))
		a.emit("LOAD")
		a.emit("PUSH", k)
		a.emit("XOR")
		a.emit("PUSH", m)
		a.emit("MUL")
		if i == 0 {
			a.emit("PUSH", 0x33)
		} else {
			a.emit("PUSH", byte(i-1))
			a.emit("LOAD")
		}
		a.emit("ADD")
		a.emit("PUSH", t)
		a.emit("SUB")
		a.jump("JNZ", "fail")
	}
	a.emit("PUSH", 1)
	a.emit("HALT")
	a.labels["fail"] = len(a.code)
	a.emit("PUSH", 0)
	a.emit("HALT")

	for at, label := range a.fixups {
		rel := a.labels[label] - (at + 2) // relative to the next instruction
		binary.LittleEndian.PutUint16(a.code[at:], uint16(int16(rel)))
	}
	enc := make([]byte, len(a.code))
	for i, b := range a.code {
		enc[i] = b ^ byte(0x5a+13*i)
	}
	write("obfuscated-oracle/src/ops.h", []byte(defs.String()))
	write("obfuscated-oracle/dist/check.vm", enc)
}
