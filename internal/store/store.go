// Package store opens the database (SQLite or PostgreSQL) and runs migrations.
package store

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
	"io/fs"
	"net/url"
	"os"
	"path/filepath"
	"strings"
	"testing/fstest"

	"github.com/pressly/goose/v3"
	"github.com/uptrace/bun"
	"github.com/uptrace/bun/dialect/pgdialect"
	"github.com/uptrace/bun/dialect/sqlitedialect"
	"github.com/uptrace/bun/driver/pgdriver"
	_ "modernc.org/sqlite" // pure-Go SQLite driver, keeps the binary static

	"github.com/flagfall/flagfall/migrations"
)

// Dialect names the database engine.
type Dialect string

const (
	SQLite   Dialect = "sqlite"
	Postgres Dialect = "postgres"
)

// Store wraps the database handle.
type Store struct {
	DB      *bun.DB
	Dialect Dialect
}

// Open connects to the database named by a sqlite:// or postgres:// URL.
//
// SQLite URLs: sqlite://path/to/file.db, or sqlite://:memory: for tests.
func Open(ctx context.Context, dbURL string) (*Store, error) {
	u, err := url.Parse(dbURL)
	if err != nil {
		return nil, fmt.Errorf("parse database URL: %w", err)
	}

	var s *Store
	switch u.Scheme {
	case "sqlite":
		s, err = openSQLite(strings.TrimPrefix(dbURL, "sqlite://"))
	case "postgres", "postgresql":
		sqldb := sql.OpenDB(pgdriver.NewConnector(pgdriver.WithDSN(dbURL)))
		s = &Store{DB: bun.NewDB(sqldb, pgdialect.New()), Dialect: Postgres}
	default:
		return nil, fmt.Errorf("unsupported database scheme %q", u.Scheme)
	}
	if err != nil {
		return nil, err
	}

	if err := s.DB.PingContext(ctx); err != nil {
		s.DB.Close()
		return nil, fmt.Errorf("connect to %s database: %w", s.Dialect, err)
	}
	return s, nil
}

func openSQLite(path string) (*Store, error) {
	memory := path == ":memory:" || path == ""
	if !memory {
		if dir := filepath.Dir(path); dir != "." {
			if err := os.MkdirAll(dir, 0o750); err != nil {
				return nil, fmt.Errorf("create database directory: %w", err)
			}
		}
	}

	pragmas := "_pragma=foreign_keys(1)&_pragma=busy_timeout(5000)&_txlock=immediate"
	var dsn string
	if memory {
		dsn = "file::memory:?" + pragmas
	} else {
		dsn = "file:" + filepath.ToSlash(path) + "?" + pragmas + "&_pragma=journal_mode(WAL)&_pragma=synchronous(NORMAL)"
	}

	sqldb, err := sql.Open("sqlite", dsn)
	if err != nil {
		return nil, err
	}
	// One connection: an in-memory database exists per connection, and a
	// single writer avoids SQLITE_BUSY under load. Reads are served from the
	// in-memory caches, so this is not the bottleneck it looks like.
	sqldb.SetMaxOpenConns(1)

	return &Store{DB: bun.NewDB(sqldb, sqlitedialect.New()), Dialect: SQLite}, nil
}

// Close closes the database.
func (s *Store) Close() error { return s.DB.Close() }

// Migrate brings the schema up to date. It is safe to call on every start.
func (s *Store) Migrate(ctx context.Context) error {
	fsys, err := expandMigrations(migrations.FS, s.Dialect)
	if err != nil {
		return err
	}
	dialect := goose.DialectSQLite3
	if s.Dialect == Postgres {
		dialect = goose.DialectPostgres
	}
	p, err := goose.NewProvider(dialect, s.DB.DB, fsys)
	if err != nil {
		return fmt.Errorf("load migrations: %w", err)
	}
	if _, err := p.Up(ctx); err != nil {
		return fmt.Errorf("run migrations: %w", err)
	}
	return nil
}

// expandMigrations replaces the dialect tokens in every migration file.
func expandMigrations(src fs.FS, d Dialect) (fs.FS, error) {
	tokens := map[Dialect]*strings.Replacer{
		SQLite:   strings.NewReplacer("{{pk}}", "INTEGER PRIMARY KEY", "{{ts}}", "TIMESTAMP"),
		Postgres: strings.NewReplacer("{{pk}}", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "{{ts}}", "TIMESTAMPTZ"),
	}[d]
	if tokens == nil {
		return nil, fmt.Errorf("unknown dialect %q", d)
	}

	out := fstest.MapFS{}
	entries, err := fs.ReadDir(src, ".")
	if err != nil {
		return nil, err
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".sql") {
			continue
		}
		b, err := fs.ReadFile(src, e.Name())
		if err != nil {
			return nil, err
		}
		body := tokens.Replace(string(b))
		if strings.Contains(body, "{{") {
			return nil, errors.New("migration " + e.Name() + " has an unknown {{token}}")
		}
		out[e.Name()] = &fstest.MapFile{Data: []byte(body)}
	}
	return out, nil
}
